// Holds simple methods that take parameters and print the results
public class PTest{


	// Multiplies the two int parameters and prints the product
	public void times(int num1, int num2){
		System.out.println(num1 * num2);
	}

	// Divides the two double parameters and prints the quotient
	public void divide(double num1, double num2){
		System.out.println(num1 / num2);
	}

	// Prints a greeting using the given name parameter
	public void sayHello(String wordInput){
		System.out.println("Hello " + wordInput);
	}
	
	
	
}
